/**
 * el - Greek keyword table of the smart-search parser (schema: ./index.ts).
 *
 * Notes for Greek:
 *  - Words are written in lower case with their accents (τόνος) and final sigma; `v()` / `vr()` /
 *    `cmp()` below also register the spelling without accents and diaeresis, which is how many
 *    people type ("ποιες μερες", "αγχος").
 *  - Nouns and adjectives are listed in the case / gender forms a question uses ("η διάθεση",
 *    "τη διάθεσή μου" with the enclitic accent, "κουρασμένος / κουρασμένη").
 *  - Month names: Intl gives the genitive ("Ιουλίου") and "Ιουλ"; the nominative, the accusative
 *    ("τον Ιούλιο") and the colloquial forms ("Ιούλη") are added as aliases.
 *  - "N units ago" is "πριν (από) Ν μέρες": the ago words stand before the number; "από" is an
 *    ago word too, so that "πριν από 3 μέρες" is understood ("πριν" then stays as a stopword).
 *  - Fused halves are number words: "εξίμισι" = 6.5, "πεντέμισι" = 5.5.
 */
import type { ComparatorRule, SearchLanguageTable } from './index';
import type { Comparator } from '../../types';

/** The word without τόνος / dialytika ("διάθεσή" -> "διαθεση", "Μαΐου" -> "μαιου"). */
function unaccented(word: string): string {
  return word.normalize('NFD').replace(/[́̈̈́]/g, '').normalize('NFC');
}

/** The word and its unaccented spelling. */
function variants(word: string): string[] {
  const plain = unaccented(word);
  return plain === word ? [word] : [word, plain];
}

/** Word list with unaccented variants (deduplicated). */
function v(...words: string[]): string[] {
  return [...new Set(words.flatMap(variants))];
}

/** Record whose keys also get their unaccented variants. */
function vr<T>(record: Record<string, T>): Record<string, T> {
  const out: Record<string, T> = {};
  for (const [key, value] of Object.entries(record)) for (const k of variants(key)) if (!(k in out)) out[k] = value;
  return out;
}

/** Comparator rule(s) for a space-separated phrase, with its unaccented variant. */
function cmp(phrase: string, comparator: Comparator): ComparatorRule[] {
  return variants(phrase).map((p) => ({ words: p.split(' '), comparator }));
}

