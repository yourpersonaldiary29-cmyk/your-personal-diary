/**
 * ru - Russian keyword table of the smart-search parser (schema: ./index.ts).
 *
 * Notes for Russian:
 *  - Russian inflects nouns, adjectives and past-tense verbs (gender and case), and the parser
 *    compares whole tokens, so the usual forms are listed explicitly ("настроение",
 *    "настроения", "настроением"; "устал", "устала", "уставший" ...).
 *  - Many people type "е" instead of "ё": `v()` / `vr()` / `cmp()` below also register every
 *    word that contains "ё" with "е" ("моё" / "мое", "весёлый" / "веселый").
 *  - Prepositions are separate words (no glued prefixes), so `prefixes` is empty.
 *  - Numbers after "меньше / больше" are in the genitive ("меньше пяти часов"): the number
 *    words list the genitive forms as well.
 *  - Month names: Intl gives the nominative ("июль"); the prepositional ("в июле") and the
 *    genitive ("с июля", "1 июля") are month aliases. "марта" / "марте" are also forms of the
 *    name Марта, so they count as a month only after "в / за / с / месяц" or before a year.
 */
import type { ComparatorRule, SearchLanguageTable } from './index';
import type { Comparator } from '../../types';

/** The word and, when it contains "ё", its spelling with "е". */
function variants(word: string): string[] {
  const plain = word.replace(/ё/g, 'е');
  return plain === word ? [word] : [word, plain];
}

/** Word list with ё/е variants (deduplicated). */
function v(...words: string[]): string[] {
  return [...new Set(words.flatMap(variants))];
}

/** Record whose keys also get their ё/е variants. */
function vr<T>(record: Record<string, T>): Record<string, T> {
  const out: Record<string, T> = {};
  for (const [key, value] of Object.entries(record)) for (const k of variants(key)) if (!(k in out)) out[k] = value;
  return out;
}

/** Comparator rule(s) for a space-separated phrase, with its ё/е variants. */
function cmp(phrase: string, comparator: Comparator): ComparatorRule[] {
  return variants(phrase).map((p) => ({ words: p.split(' '), comparator }));
}

