/**
 * pl - Polish keyword table of the smart-search parser (schema: ./index.ts).
 *
 * Notes for Polish:
 *  - Words are written in lower case with Polish diacritics (ą ć ę ł ń ó ś ź ż); `v()` / `vr()` /
 *    `cmp()` below also register the spelling without diacritics, which many people type
 *    ("sie", "mniej niz", "zmeczony").
 *  - Polish inflects nouns and adjectives in seven cases, so the usual case forms are listed
 *    explicitly (dzień / dni / dnia / dniu / dniach, nastrój / nastroju / nastrojem, ...), as are
 *    the masculine and feminine forms of adjectives and past-tense verbs (spałem / spałam).
 *  - Several short month names from Intl are also ordinary words: "sie" (= "się" typed without
 *    diacritics), "lis" (fox), "cze" (hi), "maj/maja/maju" (and "mają" without diacritics): they
 *    count as a month only with a lead word before ("w maju", "od sierpnia") or a year after.
 *  - "N units ago" is "N dni temu", "tydzień temu" (the ago word stands after the unit).
 */
import type { ComparatorRule, SearchLanguageTable } from './index';
import type { Comparator } from '../../types';

const PLAIN: Record<string, string> = { ą: 'a', ć: 'c', ę: 'e', ł: 'l', ń: 'n', ó: 'o', ś: 's', ź: 'z', ż: 'z' };

/** The word and its spelling without diacritics. */
function variants(word: string): string[] {
  const plain = word.replace(/[ąćęłńóśźż]/g, (c) => PLAIN[c]);
  return plain === word ? [word] : [word, plain];
}

/** Word list with diacritic-free variants (deduplicated). */
function v(...words: string[]): string[] {
  return [...new Set(words.flatMap(variants))];
}

/** Record whose keys also get their diacritic-free variants. */
function vr<T>(record: Record<string, T>): Record<string, T> {
  const out: Record<string, T> = {};
  for (const [key, value] of Object.entries(record)) for (const k of variants(key)) if (!(k in out)) out[k] = value;
  return out;
}

/** Comparator rule(s) for a space-separated phrase, with its diacritic-free variant. */
function cmp(phrase: string, comparator: Comparator): ComparatorRule[] {
  return variants(phrase).map((p) => ({ words: p.split(' '), comparator }));
}

