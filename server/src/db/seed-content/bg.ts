/**
 * bg - demo texts ("Load sample data"). Same fields and pool sizes as en.ts (see README.md).
 *
 * Bulgarian first-person past forms ("чувствах", "спах") do not show the writer's gender; adjectives
 * would ("уморен / уморена"), so "уморено" (search example 2) describes the body and the feeling,
 * never the writer. Bulgarian has no cases, so names can stand inside a sentence as they are; only
 * "Мама" / "Татко" lose their capital there. Numbers take the count forms "часа" / "минути".
 */
import type { SeedContent } from './types';

/** As chips "Мама" / "Татко" start with a capital; inside a sentence they are common nouns ("Днес говорих с мама."). */
const IN_SENTENCE: Record<string, string> = { Мама: 'мама', Татко: 'татко' };

/** "А", "А и Б". */
function joinNames(names: string[]): string {
  const words = names.map((name) => IN_SENTENCE[name] ?? name);
  if (words.length <= 1) return words.join('');
  return `${words.slice(0, -1).join(', ')} и ${words[words.length - 1]}`;
}

