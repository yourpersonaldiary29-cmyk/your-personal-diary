const plural = new Intl.PluralRules('ar');

/** The counted noun after a number: plural for 3-10 ("5 ساعات"), singular otherwise ("4.5 ساعة", "30 دقيقة"). */
function counted(value: number, singular: string, few: string): string {
  return plural.select(value) === 'few' ? few : singular;
}

