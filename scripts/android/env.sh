#!/usr/bin/env bash
# The Android build environment for Git Bash - the same variables scripts/android/env.ps1 sets for
# PowerShell (the PowerShell scripts are the ones that build; this file is for ad-hoc commands):
#
#     source scripts/android/env.sh
#     (cd android && ./gradlew.bat assembleDebug)
#
# Never setx: the processes of the Claude desktop app run in an MSIX container with a redirected
# AppData, which is why the tools live under C:\Users\AVI\Tools. Overrides: DIARY_ANDROID_JDK,
# DIARY_ANDROID_SDK, DIARY_GRADLE_USER_HOME.

export PATH="/c/Users/AVI/AppData/Local/Programs/nodejs:/c/Users/AVI/.cargo/bin:$PATH"

export JAVA_HOME="${DIARY_ANDROID_JDK:-C:\\Users\\AVI\\Tools\\jdk-21}"
export ANDROID_HOME="${DIARY_ANDROID_SDK:-C:\\Users\\AVI\\Tools\\android-sdk}"
export ANDROID_SDK_ROOT="$ANDROID_HOME"
export GRADLE_USER_HOME="${DIARY_GRADLE_USER_HOME:-C:\\Users\\AVI\\Tools\\gradle-home}"
mkdir -p "$(cygpath -u "$GRADLE_USER_HOME")"

export PATH="$(cygpath -u "$JAVA_HOME")/bin:$(cygpath -u "$ANDROID_HOME")/platform-tools:$PATH"

# android/local.properties (generated, not committed): sdk.dir with escaped backslashes and colon.
_diary_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
if [ -d "$_diary_root/android" ]; then
  _sdk_escaped="$(printf '%s' "$ANDROID_HOME" | sed -e 's/\\/\\\\/g' -e 's/:/\\:/g')"
  printf '## Generated by scripts/android/env.sh (not committed): the Android SDK used by Gradle.\nsdk.dir=%s\n' "$_sdk_escaped" > "$_diary_root/android/local.properties"
fi
unset _diary_root _sdk_escaped

echo "JAVA_HOME=$JAVA_HOME"
echo "ANDROID_HOME=$ANDROID_HOME"
echo "GRADLE_USER_HOME=$GRADLE_USER_HOME"
