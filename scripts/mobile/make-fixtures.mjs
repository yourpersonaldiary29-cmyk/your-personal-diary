const KDF_PASSWORD_COUNT = 62;

function sha256Hex(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

/** Deterministic 16-byte salt of vector `index` (so the vectors file is stable across runs). */
function vectorSalt(index) {
  if (index === 0) return Buffer.alloc(16, 0);
  return createHash('sha256').update(`mpd-kdf-vector-${index}`).digest().subarray(0, 16);
}

async function main(outDir) {
  if (KDF_PASSWORDS.length !== KDF_PASSWORD_COUNT) throw new Error(`expected ${KDF_PASSWORD_COUNT} passwords, have ${KDF_PASSWORDS.length}`);
  // Before any work: never start on a directory that would be refused at the end.
  const problem = outputDirProblem(outDir);
  if (problem) throw new FixturesUsageError(problem);

  const writeFile = (relative, content) => {
    const file = path.join(outDir, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    return relative.split(path.sep).join('/');
  };

  // The server sources, loaded natively (no mobile alias plugin): node:crypto, node:fs, sql.js for Node.
  const server = await createServer({
    configFile: false,
    root: path.join(root, 'server'),
    logLevel: 'error',
    appType: 'custom',
    resolve: { alias: { '@shared': path.join(root, 'shared') } },
    server: { middlewareMode: true, hmr: false, ws: false, watch: null },
    optimizeDeps: { noDiscovery: true, include: [] },
  });
  const runner = createServerModuleRunner(server.environments.ssr, { hmr: false });
  const load = (module) => runner.import(`/src/${module}`);

  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'mpd-fixtures-'));
  try {
    const [{ loadConfig }, deviceKeyModule, { DiaryAuthService }, { seedDemoData }, entriesRepo, backup, kdf, container, mailSettings, vaultModule, constants] =
      await Promise.all([
        load('config.ts'),
        load('security/device-key.ts'),
        load('security/auth-service.ts'),
        load('db/seed.ts'),
        load('db/entries-repo.ts'),
        load('backup/backup.ts'),
        load('security/kdf.ts'),
        load('security/container.ts'),
        load('mail/settings.ts'),
        load('security/vault.ts'),
        runner.import(path.join(root, 'shared', 'constants.ts').split(path.sep).join('/')),
      ]);

    // 1. A desktop data directory: register, write a diary, make two backups, shut down.
    const config = loadConfig(['--data-dir', dataDir, '--port', '0'], {});
    const deviceKey = deviceKeyModule.loadOrCreateDeviceKey(config.deviceKeyFile);
    const auth = new DiaryAuthService(config, deviceKey);
    const { token, account } = await auth.register({ ...ACCOUNT, rememberMe: true });
    const ctx = await auth.authenticate(token);
    if (!ctx) throw new Error('the fixture session did not authenticate');

    const seeded = seedDemoData(ctx.db, 45, 20260930, '2026-09-28', 'he', null);
    for (const entry of EXTRA_ENTRIES) entriesRepo.createEntry(ctx.db, entriesRepo.validateEntryInput(entry));
    const entries = entriesRepo.listEntriesFull(ctx.db, null, null);
    const habitCount = Number(ctx.db.scalar('SELECT COUNT(*) FROM habits') ?? 0);
    const habitLogCount = Number(ctx.db.scalar('SELECT COUNT(*) FROM habit_logs') ?? 0);
    const diaryKey = ctx.vault.getKey();

    const backupAccount = await backup.createBackupBytes(ctx.vault, ctx.account);
    const backupOwn = await backup.createBackupBytes(ctx.vault, ctx.account, BACKUP_PASSWORD);
    const imageAtBackup = Buffer.from(vaultModule.exportImage(ctx.db));
    const smtpPasswordEnc = mailSettings.encryptSmtpPassword(SMTP_PASSWORD, deviceKey);
    await auth.shutdown();

    const diaryBytes = fs.readFileSync(path.join(config.usersDir, account.dbFile));
    const diaryPlain = container.decryptContainer(diaryBytes, diaryKey).plain;
    const sessionsJson = JSON.parse(fs.readFileSync(config.sessionsFile, 'utf8'));
    const accountsJson = JSON.parse(fs.readFileSync(config.accountsFile, 'utf8'));
    const storedAccount = (accountsJson.accounts ?? accountsJson).find?.((a) => a.id === account.id) ?? account;
    if (sessionsJson.sessions.length !== 1) throw new Error('expected exactly one persisted session');

    // 2. Write the files (the directory may have changed while the diary was built: check again).
    const changed = outputDirProblem(outDir);
    if (changed) throw new FixturesUsageError(changed);
    removeGeneratedFiles(outDir);
    const files = {
      accounts: writeFile(path.join('desktop-data', 'accounts.json'), fs.readFileSync(config.accountsFile)),
      sessions: writeFile(path.join('desktop-data', 'sessions.json'), fs.readFileSync(config.sessionsFile)),
      deviceKey: writeFile(path.join('desktop-data', 'device.key'), fs.readFileSync(config.deviceKeyFile)),
      diary: writeFile(path.join('desktop-data', 'users', `${account.dbFile}${FIXTURE_SUFFIX}`), diaryBytes),
      backupAccountPassword: writeFile(`backup-account-password.mpd${FIXTURE_SUFFIX}`, backupAccount),
      backupOwnPassword: writeFile(`backup-own-password.mpd${FIXTURE_SUFFIX}`, backupOwn),
    };

    // 3. scrypt vectors through the app's own deriveSecret (NFKC + scrypt N=2^15, r=8, p=1, 64 bytes).
    const vectors = [];
    for (let i = 0; i < KDF_PASSWORDS.length; i++) {
      const [label, password] = KDF_PASSWORDS[i];
      const salt = vectorSalt(i);
      const secret = await kdf.deriveSecret(password, salt);
      vectors.push({ label, password, saltHex: salt.toString('hex'), secretHex: secret.toString('hex') });
    }
    writeFile(
      'kdf-vectors.json',
      JSON.stringify({ kdf: kdf.DEFAULT_KDF, secretLength: kdf.SECRET_LENGTH, generatedWith: `node ${process.version} (node:crypto scrypt)`, vectors }, null, 2),
    );

    // 4. The manifest.
    const manifest = {
      note: `${MANIFEST_NOTE_PREFIX} from the real server modules under Node.js. Fictional data only.`,
      generatedWith: `node ${process.version}`,
      appVersion: constants.APP_VERSION,
      files,
      account: {
        id: account.id,
        username: ACCOUNT.username,
        password: ACCOUNT.password,
        dbFile: account.dbFile,
        kdf: storedAccount.kdf,
        verifierHex: storedAccount.verifierHex,
        recoveryWrappedKey: storedAccount.recoveryWrappedKey,
      },
      diaryKeyHex: diaryKey.toString('hex'),
      deviceKeyHex: deviceKey.toString('hex'),
      session: {
        token,
        tokenHash: sessionsJson.sessions[0].tokenHash,
        wrappedKeyBase64: sessionsJson.sessions[0].wrappedKeyBase64,
      },
      diary: {
        fileSha256: sha256Hex(diaryBytes),
        plainSha256: sha256Hex(diaryPlain),
        plainLength: diaryPlain.length,
      },
      backups: {
        accountPassword: { password: ACCOUNT.password, fileSha256: sha256Hex(backupAccount), plainSha256: sha256Hex(imageAtBackup), plainLength: imageAtBackup.length },
        ownPassword: { password: BACKUP_PASSWORD, fileSha256: sha256Hex(backupOwn), plainSha256: sha256Hex(imageAtBackup), plainLength: imageAtBackup.length },
      },
      content: {
        entries: entries.length,
        seededEntries: seeded.entries,
        habits: habitCount,
        habitLogs: habitLogCount,
        // The whole diary text as the repository returns it: the phone must read the same rows.
        entriesSha256: sha256Hex(Buffer.from(JSON.stringify(entries), 'utf8')),
        lastEntry: entries.find((e) => e.title === EXTRA_ENTRIES[0].title) ?? null,
      },
      mail: { password: SMTP_PASSWORD, passwordEnc: smtpPasswordEnc },
    };
    writeFile('manifest.json', JSON.stringify(manifest, null, 2));

    console.log(`[make-fixtures] ${entries.length} entries, ${habitCount} habits, diary ${diaryBytes.length} bytes -> ${outDir}`);
  } finally {
    fs.rmSync(dataDir, { recursive: true, force: true });
    await runner.close();
    await server.close();
  }
}

/** True when this file is the script Node was started with (a test imports it for its helpers). */
function isMainModule() {
  if (!process.argv[1]) return false;
  try {
    const started = fs.realpathSync(path.resolve(process.argv[1]));
    const self = fs.realpathSync(fileURLToPath(import.meta.url));
    return process.platform === 'win32' ? started.toLowerCase() === self.toLowerCase() : started === self;
  } catch {
    return false;
  }
}

if (isMainModule()) {
  try {
    await main(parseOutDir(process.argv.slice(2)));
  } catch (error) {
    if (!(error instanceof FixturesUsageError)) throw error;
    console.error(`[make-fixtures] ${error.message}\n${USAGE}`);
    process.exitCode = 2;
  }
}
