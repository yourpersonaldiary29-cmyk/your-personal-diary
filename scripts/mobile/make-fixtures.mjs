/**
 * Generates the byte-compatibility fixtures of the Android core (mobile/test/fixtures) by running
 * the REAL server modules (server/src) under Node.js with node:crypto - exactly what the desktop
 * app runs. The mobile test suite (mobile/test/compat) then opens these files through the mobile
 * shims (@noble scrypt / AES-GCM, the Buffer polyfill, the sql.js browser build) and must get the
 * same bytes.
 *
 * What it writes (all data is fictional):
 *   desktop-data/                       a data directory as the desktop server leaves it
 *     accounts.json                     one account (verifier, recovery copy of the diary key)
 *     sessions.json                     one "remember me" session (diary key wrapped with device.key)
 *     device.key                        the 32-byte device key
 *     users/<id>.mpd.fixture            the encrypted diary (the real name is <id>.mpd; the suffix
 *                                       keeps the fixture out of the "*.mpd" ignore rule)
 *   backup-account-password.mpd.fixture a backup protected by the account password
 *   backup-own-password.mpd.fixture     a backup protected by a separate password
 *   kdf-vectors.json                    deriveSecret() of 62 passwords (security/kdf.ts under Node)
 *   manifest.json                       passwords, keys and digests the tests compare against
 *
 * Salts and nonces are random, so every run produces different files; the committed set is one
 * consistent snapshot. The server modules are loaded from their TypeScript sources through
 * Vite's module runner (as vitest does for the server tests); nothing is written outside a
 * temporary directory and mobile/test/fixtures.
 *
 * Usage: node scripts/mobile/make-fixtures.mjs               (rewrites mobile/test/fixtures)
 *        node scripts/mobile/make-fixtures.mjs --out=<dir>   (writes a fresh set elsewhere; run the
 *            suite against it with MPD_FIXTURES_DIR=<dir> to check the generator without touching
 *            the committed snapshot)
 *
 * The target directory must be new, empty, or an earlier output of this generator (it holds a
 * manifest.json this script wrote); anything else is refused and left untouched. In a directory it
 * accepts, the generator replaces only its own files (GENERATED_PATHS) - other files stay.
 */
import { createHash } from 'node:crypto';
