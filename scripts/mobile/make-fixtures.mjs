const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DEFAULT_OUT_DIR = path.join(root, 'mobile', 'test', 'fixtures');
const USAGE = 'Usage: node scripts/mobile/make-fixtures.mjs [--out=<new, empty or earlier fixtures directory>]';

/** Suffix of every container fixture ("*.mpd" itself is ignored by .gitignore: diary data is never committed). */
const FIXTURE_SUFFIX = '.fixture';

/** How the `note` of a manifest.json written by this generator starts: the mark of a fixtures directory. */
export const MANIFEST_NOTE_PREFIX = 'Generated by scripts/mobile/make-fixtures.mjs';

/** Everything this generator writes, relative to the output directory - and all it ever deletes there. */
export const GENERATED_PATHS = [
  'desktop-data',
  `backup-account-password.mpd${FIXTURE_SUFFIX}`,
  `backup-own-password.mpd${FIXTURE_SUFFIX}`,
  'kdf-vectors.json',
  'manifest.json',
];

/** A mistake on the command line, or an output directory that must not be touched (exit code 2). */
export class FixturesUsageError extends Error {}

/** The output directory named by the arguments (absolute). Throws FixturesUsageError for anything unclear. */
export function parseOutDir(args) {
  let outDir = DEFAULT_OUT_DIR;
  for (const arg of args) {
    if (!arg.startsWith('--out=')) throw new FixturesUsageError(`unknown argument "${arg}"`);
    const value = arg.slice('--out='.length);
    // An empty value would resolve to the current directory.
    if (value.trim() === '') throw new FixturesUsageError('--out needs a directory: --out=<dir>');
    outDir = path.resolve(value);
  }
  return outDir;
}

/** True when `dir` holds a manifest.json written by this generator. */
function hasGeneratorManifest(dir) {
  try {
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
    return typeof manifest?.note === 'string' && manifest.note.startsWith(MANIFEST_NOTE_PREFIX);
  } catch {
    return false;
  }
}

/**
 * Why the fixtures must not be written to `dir`, or null when they may: the directory does not
 * exist yet, is empty, or is an earlier output of this generator. (The generator deletes its old
 * files there, so it never works in a directory it cannot recognise as its own.)
 */
export function outputDirProblem(dir) {
  let stat;
  try {
    stat = fs.lstatSync(dir);
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
  if (!stat.isDirectory()) return `${dir} exists and is not a directory`;
  const names = fs.readdirSync(dir);
  if (names.length === 0 || hasGeneratorManifest(dir)) return null;
  const found = names.slice(0, 5).join(', ') + (names.length > 5 ? ', ...' : '');
  return `${dir} is not empty and is not a fixtures directory of this generator (no manifest.json written by it; found: ${found}). Nothing was changed - choose a new or empty directory.`;
}

/**
 * Removes the previous output from `dir`: only GENERATED_PATHS, never the directory itself or other
 * files in it. manifest.json stays until the new one replaces it, so an interrupted run leaves a
 * directory the next run still recognises.
 */
export function removeGeneratedFiles(dir) {
  for (const relative of GENERATED_PATHS) {
    if (relative === 'manifest.json') continue;
    fs.rmSync(path.join(dir, relative), { recursive: true, force: true });
  }
}

